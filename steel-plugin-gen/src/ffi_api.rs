//! Generated typed wrapper over the `SteelInterface` C function table.
//!
//! `steel-plugin-gen` reads the parsed ABI and emits one Dart method per
//! interface function, including the `asFunction` signature. This generated
//! plumbing is internal to the binding transport; plugin-facing code only sees
//! `SteelBinding` and the generated host API.

use crate::model::{Api, RustType};

/// Generated output path for the Dart FFI wrapper.
pub const FFI_API_PATH: &str = "clients/dart/lib/src/steel/ffi_api.dart";

fn camel_case(name: &str) -> String {
    let mut output = String::new();
    let mut upper = false;
    for character in name.chars() {
        if character == '_' {
            upper = true;
        } else if upper {
            output.extend(character.to_uppercase());
            upper = false;
        } else {
            output.push(character);
        }
    }
    output
}

fn scalar(name: &str) -> Option<&'static str> {
    Some(match name {
        "u8" | "u16" | "u32" | "u64" | "usize" | "i8" | "i16" | "i32" | "i64" | "isize" => "int",
        "f32" | "f64" => "double",
        "bool" => "int",
        _ => return None,
    })
}

fn ffi_element(ty: &RustType) -> String {
    match ty {
        RustType::Named(name) => match name.as_str() {
            "u8" => "Uint8".to_owned(),
            "i8" | "c_char" => "Int8".to_owned(),
            "u16" => "Uint16".to_owned(),
            "i16" => "Int16".to_owned(),
            "u32" => "Uint32".to_owned(),
            "i32" => "Int32".to_owned(),
            "u64" => "Uint64".to_owned(),
            "i64" => "Int64".to_owned(),
            "usize" => "UintPtr".to_owned(),
            "isize" => "IntPtr".to_owned(),
            "f32" => "Float".to_owned(),
            "f64" => "Double".to_owned(),
            "bool" => "Uint8".to_owned(),
            "c_void" => "Void".to_owned(),
            other => other.to_owned(),
        },
        RustType::Pointer { mutable, elem } => {
            let _ = mutable;
            format!("Pointer<{}>", ffi_element(elem))
        }
        _ => "Void".to_owned(),
    }
}

fn dart_type(ty: &RustType) -> String {
    match ty {
        RustType::Named(name) => scalar(name).map_or_else(
            || name.rsplit("::").next().unwrap_or(name).to_owned(),
            str::to_owned,
        ),
        RustType::Pointer { mutable, elem } => {
            let _ = mutable;
            format!("Pointer<{}>", ffi_element(elem))
        }
        RustType::Option(inner) => match inner.as_ref() {
            RustType::Named(name) => format!(
                "Pointer<NativeFunction<{}>>",
                name.rsplit("::").next().unwrap_or(name)
            ),
            RustType::FnPtr(_) => "Pointer<Void>".to_owned(),
            other => dart_type(other),
        },
        RustType::FnPtr(_) => "Pointer<Void>".to_owned(),
        RustType::Tuple(_) | RustType::Unit => "void".to_owned(),
        RustType::Unknown(name) => name.clone(),
    }
}

fn dart_return(ty: &Option<RustType>) -> String {
    ty.as_ref().map_or_else(|| "void".to_owned(), dart_type)
}

fn parameter(ty: &RustType) -> String {
    dart_type(ty)
}

fn emit_method(field: &str, signature: &crate::model::FnSignature) -> String {
    let name = camel_case(field);
    let params: Vec<String> = signature
        .inputs
        .iter()
        .enumerate()
        .map(|(index, ty)| format!("{} arg{index}", parameter(ty)))
        .collect();
    let parameters = params.join(", ");
    let args: Vec<String> = (0..signature.inputs.len())
        .map(|index| format!("arg{index}"))
        .collect();
    let return_type = dart_return(&signature.output);
    let function_type = format!(
        "{} Function({})",
        return_type,
        signature
            .inputs
            .iter()
            .map(parameter)
            .collect::<Vec<_>>()
            .join(", ")
    );
    let call = format!("function({})", args.join(", "));
    let body = if return_type == "void" {
        format!("    {call};")
    } else {
        format!("    return {call};")
    };
    format!(
        "  /// Calls `{field}`.\n  {return_type} {name}({parameters}) {{\n    final pointer = _interface.ref.{field};\n    if (pointer == nullptr) {{\n      throw SteelHostException('{field} is unavailable');\n    }}\n    final function = pointer.asFunction<{function_type}>();\n{body}\n  }}\n"
    )
}

/// Renders `clients/dart/lib/src/steel/ffi_api.dart`.
#[must_use]
pub fn emit_ffi_api(api: &Api) -> String {
    let mut output = String::from(
        "// Generated by steel-plugin-gen. Do not edit.\n\nimport 'dart:ffi';\n\nimport '../bindings.g.dart';\n\n/// Thrown when a host ABI call cannot be made.\nfinal class SteelHostException implements Exception {\n  SteelHostException(this.message);\n  final String message;\n  @override\n  String toString() => 'SteelHostException: $message';\n}\n\n/// Typed calls over [SteelInterface].\nfinal class SteelFfi {\n  SteelFfi(this._interface);\n\n  final Pointer<SteelInterface> _interface;\n\n",
    );
    let Some(interface) = api.structs.iter().find(|s| s.name == api.host_interface) else {
        output.push_str("}\n");
        return output;
    };
    for field in &interface.fields {
        let inner = match &field.ty {
            RustType::Option(inner) => inner.as_ref(),
            _ => continue,
        };
        let signature = match inner {
            RustType::Named(name) => api
                .function_types
                .iter()
                .find(|function| function.name == *name)
                .map(|function| &function.signature),
            RustType::FnPtr(signature) => Some(signature.as_ref()),
            _ => None,
        };
        if let Some(signature) = signature {
            output.push_str(&emit_method(&field.name, signature));
            output.push('\n');
        }
    }
    output.push_str("}\n");
    output
}
