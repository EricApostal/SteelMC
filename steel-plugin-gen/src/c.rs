//! C header emitter.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::model::{
    Api, FnSignature, RustType, collect_synthetic_fn_types, function_types_in_dependency_order,
    synthetic_fn_name,
};

const C_KEYWORDS: &[&str] = &[
    "auto",
    "break",
    "case",
    "char",
    "const",
    "continue",
    "default",
    "do",
    "double",
    "else",
    "enum",
    "extern",
    "float",
    "for",
    "goto",
    "if",
    "inline",
    "int",
    "long",
    "register",
    "restrict",
    "return",
    "short",
    "signed",
    "sizeof",
    "static",
    "struct",
    "switch",
    "typedef",
    "union",
    "unsigned",
    "void",
    "volatile",
    "while",
    "_Alignas",
    "_Alignof",
    "_Atomic",
    "_Bool",
    "_Complex",
    "_Generic",
    "_Imaginary",
    "_Noreturn",
    "_Static_assert",
    "_Thread_local",
];

struct Context {
    aliases: BTreeSet<String>,
    synthetic: BTreeMap<String, FnSignature>,
}

impl Context {
    fn new(api: &Api) -> Self {
        Self {
            aliases: api
                .function_types
                .iter()
                .map(|function| function.name.clone())
                .collect(),
            synthetic: collect_synthetic_fn_types(api),
        }
    }

    fn ty(&self, ty: &RustType) -> String {
        match ty {
            RustType::Named(name) => {
                if ty.is_c_void() {
                    return "void".to_owned();
                }
                match name.as_str() {
                    "u8" | "bool" => "uint8_t".to_owned(),
                    "u16" => "uint16_t".to_owned(),
                    "u32" => "uint32_t".to_owned(),
                    "u64" => "uint64_t".to_owned(),
                    "i8" => "int8_t".to_owned(),
                    "i16" => "int16_t".to_owned(),
                    "i32" => "int32_t".to_owned(),
                    "i64" => "int64_t".to_owned(),
                    "usize" => "size_t".to_owned(),
                    "isize" => "ptrdiff_t".to_owned(),
                    "f32" => "float".to_owned(),
                    "f64" => "double".to_owned(),
                    "c_void" => "void".to_owned(),
                    _ => name.clone(),
                }
            }
            RustType::Option(inner) => self.option_ty(inner),
            RustType::Pointer { mutable, elem } => {
                let qualifier = if *mutable { "" } else { "const " };
                if elem.is_c_void() {
                    format!("{qualifier}void*")
                } else if matches!(elem.as_ref(), RustType::Pointer { .. }) {
                    let inner = self.ty(elem);
                    let inner = inner.trim_start_matches("const ");
                    format!("{qualifier}{inner}*")
                } else {
                    format!("{qualifier}{}*", self.ty(elem))
                }
            }
            RustType::FnPtr(signature) => synthetic_fn_name(signature),
            RustType::Tuple(_) | RustType::Unit => "void".to_owned(),
            RustType::Unknown(rust_type) => rust_type.clone(),
        }
    }

    fn option_ty(&self, inner: &RustType) -> String {
        match inner {
            RustType::Named(name) if self.aliases.contains(name) => name.clone(),
            RustType::FnPtr(signature) => synthetic_fn_name(signature),
            other => self.ty(other),
        }
    }

    fn function_pointer(&self, name: &str, signature: &FnSignature) -> String {
        let output = signature
            .output
            .as_ref()
            .map_or_else(|| "void".to_owned(), |output| self.ty(output));
        let inputs = if signature.inputs.is_empty() {
            "void".to_owned()
        } else {
            signature
                .inputs
                .iter()
                .map(|input| self.ty(input))
                .collect::<Vec<_>>()
                .join(", ")
        };
        format!("{output} (*{name})({inputs})")
    }
}

fn field_name(name: &str) -> String {
    if name.chars().all(|character| character.is_ascii_digit()) {
        return format!("_{name}");
    }
    if C_KEYWORDS.contains(&name) {
        return format!("_{name}");
    }
    name.to_owned()
}

/// Renders the `steel_extension.h` header.
#[must_use]
pub fn emit_header(api: &Api) -> String {
    let context = Context::new(api);
    let mut out = String::new();
    out.push_str("/* Generated by steel-plugin-gen. Do not edit. */\n");
    out.push_str("#ifndef STEEL_EXTENSION_H\n");
    out.push_str("#define STEEL_EXTENSION_H\n\n");
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include <stddef.h>\n\n");
    let _ = writeln!(out, "#define STEEL_API_VERSION {}", api.api_version);
    out.push('\n');

    out.push_str("/* Forward declarations. */\n");
    for definition in &api.structs {
        let _ = writeln!(
            out,
            "typedef struct {} {};",
            definition.name, definition.name
        );
    }
    out.push('\n');

    out.push_str("/* Function pointer types. */\n");
    for (name, signature) in &context.synthetic {
        let _ = writeln!(
            out,
            "typedef {};",
            context.function_pointer(name, signature)
        );
    }
    for function in function_types_in_dependency_order(api) {
        if let Some(target) = &function.alias_of {
            let _ = writeln!(out, "typedef {target} {};", function.name);
        } else {
            let _ = writeln!(
                out,
                "typedef {};",
                context.function_pointer(&function.name, &function.signature)
            );
        }
    }
    out.push('\n');

    out.push_str("/* Numeric constants. */\n");
    for constant in &api.constants {
        let _ = writeln!(out, "#define {} {}", constant.name, constant.value);
    }
    out.push('\n');

    out.push_str("/* Struct definitions. */\n");
    for definition in &api.structs {
        let _ = writeln!(out, "struct {} {{", definition.name);
        if definition.fields.is_empty() {
            out.push_str("    uint8_t _reserved;\n");
        }
        for field in &definition.fields {
            let _ = writeln!(
                out,
                "    {} {};",
                context.ty(&field.ty),
                field_name(&field.name)
            );
        }
        out.push_str("};\n\n");
    }

    out.push_str("#endif /* STEEL_EXTENSION_H */\n");
    out
}
