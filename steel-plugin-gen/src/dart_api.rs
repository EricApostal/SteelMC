//! Emitter for the plugin-facing Dart API.
//!
//! The emitter consumes the `steel-api/steel_api.json` model produced by
//! `steel-api-codegen` and renders one Dart class per host class. Every method
//! is a thin call through `SteelBinding.ptrcall`, so the generated code never
//! contains FFI signatures or per-method marshalling.

use std::fmt::Write as _;

use serde::Deserialize;

use crate::dart::snake_to_lower_camel;

/// Workspace-relative output path of the generated plugin API.
pub const DART_API_PATH: &str = "clients/dart/lib/src/steel/generated.dart";

#[derive(Debug, Deserialize)]
struct Api {
    api_version: u32,
    classes: Vec<Class>,
}

#[derive(Debug, Deserialize)]
struct Class {
    name: String,
    inherits: Option<String>,
    handle: String,
    methods: Vec<Method>,
}

#[derive(Debug, Deserialize)]
struct Method {
    name: String,
    hash: u32,
    #[serde(rename = "static")]
    is_static: bool,
    #[serde(default)]
    args: Vec<Argument>,
    #[serde(rename = "return", default)]
    returns: Option<String>,
    #[serde(default)]
    returns_class: Option<String>,
}

#[derive(Debug, Deserialize)]
struct Argument {
    name: String,
    #[serde(rename = "type")]
    ty: String,
}

/// Renders `clients/dart/lib/src/steel/generated.dart` from the API JSON.
pub fn emit_dart_api(json: &str) -> Result<String, String> {
    let api: Api =
        serde_json::from_str(json).map_err(|error| format!("invalid API JSON: {error}"))?;
    let mut output = String::from(
        "// Generated by steel-plugin-gen. Do not edit.\n\nimport 'binding.dart';\nimport 'model.dart';\n\n/// Base type for every host object exposed to plugins.\n///\n/// The host class `Object` is rendered as [SteelObject] because `Object` is a\n/// `dart:core` type. Subclasses carry the handle fields the host needs and\n/// perform every operation through [binding].\nabstract class SteelObject {\n  const SteelObject(this.binding);\n\n  /// Transport used for every host call on this object.\n  final SteelBinding binding;\n\n  /// Reference passed to instance method calls.\n  SteelRef get reference;\n}\n",
    );
    writeln!(
        output,
        "\n/// Host API version exposed by `steel-api/steel_api.json`.\nconst int steelHostApiVersion = {};\n",
        api.api_version
    )
    .map_err(|error| error.to_string())?;
    for class in &api.classes {
        emit_class(&mut output, &api.classes, class)?;
    }
    Ok(output)
}

fn class_base(class: &Class) -> &str {
    match class.inherits.as_deref() {
        Some("Object") | None => "SteelObject",
        Some(parent) => parent,
    }
}

fn handle_doc(handle: &str) -> Option<&'static str> {
    Some(match handle {
        "world" => "Host world id.",
        "block" => "Registry block id.",
        "block_state" => "Registry block state id.",
        "item" => "Registry item id.",
        "item_stack" | "nbt" => "Host-owned reference.",
        _ => return None,
    })
}

fn emit_class(output: &mut String, classes: &[Class], class: &Class) -> Result<(), String> {
    if class.name == "Object" {
        return Ok(());
    }
    let name = &class.name;
    let base = class_base(class);
    let parent = class
        .inherits
        .as_deref()
        .filter(|parent| *parent != "Object")
        .map(|parent| {
            classes
                .iter()
                .find(|candidate| candidate.name == parent)
                .ok_or_else(|| format!("class `{name}` inherits unknown `{parent}`"))
        })
        .transpose()?;
    if let Some(parent) = parent
        && parent.handle != class.handle
    {
        return Err(format!(
            "class `{name}` handle `{}` differs from `{}` handle `{}`",
            class.handle, parent.name, parent.handle
        ));
    }
    writeln!(output, "\n/// Host API for `{name}`.")
        .and_then(|()| writeln!(output, "class {name} extends {base} {{"))
        .map_err(|error| error.to_string())?;
    emit_handle(output, name, class, parent.is_some())?;
    for method in &class.methods {
        emit_method(output, class, method)?;
    }
    output.push_str("}\n");
    Ok(())
}

fn emit_handle(
    output: &mut String,
    name: &str,
    class: &Class,
    inherited: bool,
) -> Result<(), String> {
    if inherited {
        let constructor = match class.handle.as_str() {
            "entity" => format!("  {name}(super.binding, super.world, super.entity);\n"),
            "world" | "block" | "block_state" | "item" => {
                format!("  {name}(super.binding, super.id);\n")
            }
            "item_stack" | "nbt" => format!("  {name}(super.binding, super.reference);\n"),
            "server" | "none" => format!("  {name}(super.binding);\n"),
            other => return Err(format!("unsupported handle `{other}` on class `{name}`")),
        };
        writeln!(output, "{constructor}").map_err(|error| error.to_string())?;
        return emit_from_ref(output, name, &class.handle);
    }
    match class.handle.as_str() {
        "entity" => {
            writeln!(
                output,
                "  {name}(super.binding, this.world, this.entity);\n"
            )
            .and_then(|()| writeln!(output, "  /// Host world id."))
            .and_then(|()| writeln!(output, "  final int world;\n"))
            .and_then(|()| writeln!(output, "  /// Entity id within [world]."))
            .and_then(|()| writeln!(output, "  final int entity;\n"))
            .and_then(|()| {
                writeln!(
                    output,
                    "  @override\n  SteelRef get reference => steelEntityRef(world, entity);\n"
                )
            })
            .map_err(|error| error.to_string())?;
        }
        "world" | "block" | "block_state" | "item" => {
            writeln!(output, "  {name}(super.binding, this.id);\n")
                .and_then(|()| {
                    writeln!(
                        output,
                        "  /// {}",
                        handle_doc(&class.handle).unwrap_or("Handle id.")
                    )
                })
                .and_then(|()| writeln!(output, "  final int id;\n"))
                .map_err(|error| error.to_string())?;
            let reference = match class.handle.as_str() {
                "world" => "steelWorldRef(id)",
                "block" => "steelBlockRef(id)",
                "block_state" => "steelBlockStateRef(id)",
                _ => "steelItemRef(id)",
            };
            writeln!(
                output,
                "  @override\n  SteelRef get reference => {reference};\n"
            )
            .map_err(|error| error.to_string())?;
        }
        "item_stack" | "nbt" => {
            writeln!(output, "  {name}(super.binding, this.reference);\n")
                .and_then(|()| writeln!(output, "  @override\n  final SteelRef reference;\n"))
                .map_err(|error| error.to_string())?;
        }
        "server" | "none" => {
            writeln!(output, "  {name}(super.binding);\n")
                .and_then(|()| {
                    writeln!(
                        output,
                        "  @override\n  SteelRef get reference => steelNoneRef();\n"
                    )
                })
                .map_err(|error| error.to_string())?;
        }
        other => return Err(format!("unsupported handle `{other}` on class `{name}`")),
    }
    emit_from_ref(output, name, &class.handle)
}

fn emit_from_ref(output: &mut String, name: &str, handle: &str) -> Result<(), String> {
    let call = match handle {
        "entity" => format!("{name}(binding, reference.index, reference.generation)"),
        "world" | "block" | "block_state" | "item" => {
            format!("{name}(binding, reference.index)")
        }
        "item_stack" | "nbt" => format!("{name}(binding, reference)"),
        "server" | "none" => format!("{name}(binding)"),
        other => return Err(format!("unsupported handle `{other}` on class `{name}`")),
    };
    writeln!(
        output,
        "  /// Wraps a host reference returned by another method.\n  factory {name}.fromRef(SteelBinding binding, SteelRef reference) =>\n      {call};"
    )
    .map_err(|error| error.to_string())?;
    if matches!(handle, "world" | "block" | "block_state" | "item") {
        writeln!(
            output,
            "\n  /// Wraps a host handle id returned by another method.\n  factory {name}.fromId(SteelBinding binding, int id) =>\n      {name}(binding, id);"
        )
        .map_err(|error| error.to_string())?;
    }
    Ok(())
}

fn emit_method(output: &mut String, class: &Class, method: &Method) -> Result<(), String> {
    let dart_name = snake_to_lower_camel(&method.name);
    let mut parameters: Vec<String> = Vec::new();
    if method.is_static {
        parameters.push("SteelBinding binding".to_owned());
    }
    for argument in &method.args {
        parameters.push(format!(
            "{} {}",
            dart_type(&argument.ty)?,
            snake_to_lower_camel(&argument.name)
        ));
    }
    let return_type = match &method.returns_class {
        Some(class) => format!("{class}?"),
        None => match method.returns.as_deref() {
            Some("BlockId") => "Block".to_owned(),
            Some("BlockStateId") => "BlockState".to_owned(),
            Some("ItemId") => "Item".to_owned(),
            other => other.map_or_else(|| Ok("void".to_owned()), dart_return)?,
        },
    };
    let arguments = method
        .args
        .iter()
        .map(|argument| {
            let param = snake_to_lower_camel(&argument.name);
            Ok(match argument.ty.as_str() {
                "BlockId" | "BlockStateId" | "ItemId" => {
                    format!("SteelArg.u32({param}.id)")
                }
                _ => format!("SteelArg.{}({param})", arg_encoder(&argument.ty)?),
            })
        })
        .collect::<Result<Vec<_>, String>>()?;
    let instance = if method.is_static {
        "steelNoneRef()"
    } else {
        "reference"
    };
    let return_kind = method_return_kind(method)?;

    writeln!(output, "\n  /// Calls `{}.{}`.", class.name, method.name)
        .and_then(|()| {
            writeln!(
                output,
                "  {}{} {dart_name}({}) {{",
                if method.is_static { "static " } else { "" },
                return_type,
                parameters.join(", ")
            )
        })
        .map_err(|error| error.to_string())?;
    let call = format!(
        "binding\n        .ptrcall(\n          '{}',\n          '{}',\n          {},\n          {},\n          <SteelArg>[{}],\n          SteelReturnKind.{},\n        )",
        class.name,
        method.name,
        method.hash,
        instance,
        arguments.join(", "),
        return_kind
    );
    if let Some(class) = &method.returns_class {
        writeln!(
            output,
            "    final returned = {call}\n        .asRef();\n    if (returned.kind == SteelConstants.steelRefNone) {{\n      return null;\n    }}\n    return {class}.fromRef(binding, returned);"
        )
        .map_err(|error| error.to_string())?;
    } else if let Some(class) = method_returns_handle(method) {
        writeln!(
            output,
            "    final returned = {call}\n        .asInt();\n    return {class}.fromId(binding, returned);"
        )
        .map_err(|error| error.to_string())?;
    } else if return_type == "void" {
        writeln!(output, "    {call};").map_err(|error| error.to_string())?;
    } else {
        writeln!(
            output,
            "    return {call}\n        .{};",
            return_decoder(method)?
        )
        .map_err(|error| error.to_string())?;
    }
    output.push_str("  }\n");
    Ok(())
}

fn method_returns_handle(method: &Method) -> Option<&'static str> {
    match method.returns.as_deref()? {
        "BlockId" => Some("Block"),
        "BlockStateId" => Some("BlockState"),
        "ItemId" => Some("Item"),
        _ => None,
    }
}

fn dart_type(ty: &str) -> Result<&'static str, String> {
    Ok(match ty {
        "i32" | "u32" => "int",
        "f32" | "f64" => "double",
        "bool" => "bool",
        "SteelStrView" => "String",
        "SteelVec3" => "Vec3",
        "SteelRef" => "SteelRef",
        "BlockId" => "Block",
        "BlockStateId" => "BlockState",
        "ItemId" => "Item",
        other => return Err(format!("unsupported argument type `{other}`")),
    })
}

fn dart_return(ty: &str) -> Result<String, String> {
    if ty == "()" {
        return Ok("void".to_owned());
    }
    dart_type(ty).map(str::to_owned)
}

fn arg_encoder(ty: &str) -> Result<&'static str, String> {
    Ok(match ty {
        "i32" => "i32",
        "u32" => "u32",
        "f32" => "f32",
        "f64" => "f64",
        "bool" => "boolean",
        "SteelStrView" => "string",
        "SteelVec3" => "vec3",
        "SteelRef" => "ref",
        "BlockId" | "BlockStateId" | "ItemId" => "u32",
        other => return Err(format!("unsupported argument type `{other}`")),
    })
}

fn method_return_kind(method: &Method) -> Result<&'static str, String> {
    if method.returns_class.is_some() {
        return Ok("ref");
    }
    Ok(match method.returns.as_deref() {
        None | Some("()") => "nothing",
        Some("i32") => "i32",
        Some("u32") => "u32",
        Some("f32") => "f32",
        Some("f64") => "f64",
        Some("bool") => "boolean",
        Some("SteelStrView") => "string",
        Some("SteelVec3") => "vec3",
        Some("SteelRef") => "ref",
        Some("BlockId" | "BlockStateId" | "ItemId") => "u32",
        Some(other) => return Err(format!("unsupported return type `{other}`")),
    })
}

fn return_decoder(method: &Method) -> Result<&'static str, String> {
    Ok(match method.returns.as_deref() {
        Some("i32" | "u32") => "asInt()",
        Some("f32" | "f64") => "asDouble()",
        Some("bool") => "asBool()",
        Some("SteelStrView") => "asString()",
        Some("SteelVec3") => "asVec3()",
        Some("SteelRef") => "asRef()",
        _ => return Err("method has no decodable return".to_owned()),
    })
}
